    public static IReadOnlyList<Province> Provinces { get; } = Definitions
        .Select((definition, index) => new Province(index + 1, definition.Name, index + 1))
        .ToList();

    public static IReadOnlyList<City> Cities { get; } = Definitions
        .SelectMany((definition, provinceIndex) =>
        {
            var provinceId = provinceIndex + 1;
            return definition.Cities.Select((cityName, cityIndex) => new City(
                provinceId * CityIdStride + cityIndex + 1,
                provinceId,
                cityName,
                cityIndex + 1));
        })
        .ToList();
